CREATE TABLE tauthor (
    nauthorid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cname VARCHAR(40) NOT NULL,
    csurname VARCHAR(60)
);
CREATE TABLE tpublishingcompany (
    npublishingcompanyid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cname VARCHAR(40) NOT NULL
);
CREATE TABLE tbook (
    nbookid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ctitle VARCHAR(255) NOT NULL,
    nauthorid INTEGER NOT NULL REFERENCES tauthor(nauthorid),
    npublishingcompanyid INTEGER NOT NULL REFERENCES tpublishingcompany(npublishingcompanyid),
    npublishingyear INTEGER
);
